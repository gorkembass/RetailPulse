from __future__ import annotations

import hashlib
import json
import logging
import shutil
import tempfile
import urllib.request
import zipfile
from datetime import UTC, datetime
from pathlib import Path

from retailpulse.ingestion.synthetic import generate_synthetic_transactions

logger = logging.getLogger(__name__)

UCI_DATASET_PAGE = "https://archive.ics.uci.edu/dataset/352/online+retail"
UCI_ARCHIVE_URL = "https://archive.ics.uci.edu/static/public/352/online+retail.zip"
UCI_ARCHIVE_MEMBER = "Online Retail.xlsx"
UCI_FILENAME = "online_retail.xlsx"
UCI_EXPECTED_SHA256 = "43465a06f2ccf7c8b5bd2892bc7defb52f97487934fe93b16ae4c3936424676d"
UCI_LICENSE = "CC BY 4.0"
UCI_CITATION = (
    "Chen, D. (2015). Online Retail [Dataset]. UCI Machine Learning Repository. "
    "https://doi.org/10.24432/C5BW33"
)

SYNTHETIC_FILENAME = "synthetic_online_retail.csv"
DOWNLOAD_TIMEOUT_SECONDS = 120


class RawDataExistsError(FileExistsError):
    pass


def sha256_of(path: Path) -> str:
    digest = hashlib.sha256()
    with path.open("rb") as handle:
        for chunk in iter(lambda: handle.read(1 << 20), b""):
            digest.update(chunk)
    return digest.hexdigest()


def _guard_existing(target: Path, force: bool) -> None:
    if target.exists() and not force:
        raise RawDataExistsError(
            f"{target} already exists. Raw data is immutable; pass force=True to replace it."
        )


def _write_metadata(metadata_path: Path, metadata: dict) -> None:
    metadata_path.write_text(json.dumps(metadata, indent=2) + "\n", encoding="utf-8")


def download_uci(raw_dir: Path, metadata_path: Path, force: bool = False) -> Path:
    """Download the UCI Online Retail workbook into the raw layer and record its provenance."""
    raw_dir.mkdir(parents=True, exist_ok=True)
    target = raw_dir / UCI_FILENAME
    _guard_existing(target, force)

    with tempfile.TemporaryDirectory() as tmp:
        archive = Path(tmp) / "online_retail.zip"
        logger.info("Downloading %s", UCI_ARCHIVE_URL)
        with (
            urllib.request.urlopen(UCI_ARCHIVE_URL, timeout=DOWNLOAD_TIMEOUT_SECONDS) as response,
            archive.open("wb") as out,
        ):
            shutil.copyfileobj(response, out)
        with zipfile.ZipFile(archive) as bundle, bundle.open(UCI_ARCHIVE_MEMBER) as member:
            staged = Path(tmp) / UCI_FILENAME
            with staged.open("wb") as out:
                shutil.copyfileobj(member, out)
        shutil.move(staged, target)

    checksum = sha256_of(target)
    if checksum != UCI_EXPECTED_SHA256:
        logger.warning(
            "Checksum %s differs from the version this project was validated against (%s). "
            "Published results may not reproduce exactly.",
            checksum,
            UCI_EXPECTED_SHA256,
        )
    _write_metadata(
        metadata_path,
        {
            "source": "uci_online_retail",
            "is_synthetic": False,
            "file": target.name,
            "url": UCI_ARCHIVE_URL,
            "dataset_page": UCI_DATASET_PAGE,
            "license": UCI_LICENSE,
            "citation": UCI_CITATION,
            "sha256": checksum,
            "retrieved_at": datetime.now(UTC).isoformat(timespec="seconds"),
        },
    )
    logger.info("Saved %s (%.1f MB)", target, target.stat().st_size / 1e6)
    return target


def write_synthetic(
    raw_dir: Path, metadata_path: Path, seed: int = 42, force: bool = False
) -> Path:
    """Write the deterministic synthetic dataset into the raw layer, labelled as synthetic."""
    raw_dir.mkdir(parents=True, exist_ok=True)
    target = raw_dir / SYNTHETIC_FILENAME
    _guard_existing(target, force)

    frame = generate_synthetic_transactions(seed=seed)
    frame.to_csv(target, index=False)
    _write_metadata(
        metadata_path,
        {
            "source": "synthetic",
            "is_synthetic": True,
            "file": target.name,
            "seed": seed,
            "rows": len(frame),
            "license": "Generated by this project; not real transaction data.",
            "sha256": sha256_of(target),
            "retrieved_at": datetime.now(UTC).isoformat(timespec="seconds"),
        },
    )
    logger.info("Wrote synthetic dataset to %s (%d rows)", target, len(frame))
    return target


def acquire(raw_dir: Path, metadata_path: Path, source: str = "auto", force: bool = False) -> Path:
    """Acquire raw data from UCI, falling back to synthetic data only when ``source='auto'``."""
    if source == "synthetic":
        return write_synthetic(raw_dir, metadata_path, force=force)
    if source == "uci":
        return download_uci(raw_dir, metadata_path, force=force)
    if source != "auto":
        raise ValueError(f"Unknown source '{source}'. Expected 'auto', 'uci' or 'synthetic'.")
    try:
        return download_uci(raw_dir, metadata_path, force=force)
    except RawDataExistsError:
        raise
    except (OSError, zipfile.BadZipFile, KeyError) as error:
        logger.error(
            "UCI download failed (%s). Falling back to SYNTHETIC data; "
            "results will not describe a real business.",
            error,
        )
        return write_synthetic(raw_dir, metadata_path, force=force)


def read_metadata(metadata_path: Path) -> dict:
    if not metadata_path.exists():
        raise FileNotFoundError(
            f"{metadata_path} not found. Run 'retailpulse ingest' before the other steps."
        )
    return json.loads(metadata_path.read_text(encoding="utf-8"))
